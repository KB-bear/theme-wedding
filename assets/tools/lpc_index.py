"""Write assets/characters/index.js (window.CHAR_INDEX) and the cast contact sheets.

Usage:  python -E -P lpc_index.py
Reads tools/lpc_characters.json (groups) and the composed sheets in assets/characters/.
Writes:
    characters/index.js
    previews/cast_named.png             named + staff characters, standing (facing camera), 3x, labelled
    previews/cast_pool.png              the guest pool, 3x, labelled
    previews/cast_anims_groom_bride.png groom & bride: walk (down/right), idle, cast, hurt, sit frames
"""
import json, os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
CH = os.path.join(ROOT, "characters")
PV = os.path.join(ROOT, "previews")
F = 64
ANIMS = {"walk": (9, 4), "idle": (2, 4), "cast": (7, 4), "hurt": (6, 1), "sit": (3, 4)}
POOLS = ["m", "f", "om", "of", "kb", "kg"]
BG = (96, 150, 84, 255)


def font(size):
    try:
        return ImageFont.load_default(size=size)
    except TypeError:
        return ImageFont.load_default()


def frame(name, anim, col, row):
    im = Image.open(os.path.join(CH, f"{name}_{anim}.png")).convert("RGBA")
    return im.crop((col * F, row * F, col * F + F, row * F + F))


def write_index(cfg):
    groups = cfg["groups"]
    names = [c["name"] for c in cfg["characters"]]
    chars = {}
    for n in names:
        e = {}
        for a in ANIMS:
            p = os.path.join(CH, f"{n}_{a}.png")
            if os.path.exists(p):
                with Image.open(p) as im:
                    assert im.size == (ANIMS[a][0] * F, ANIMS[a][1] * F), (p, im.size)
                e[a] = f"assets/characters/{n}_{a}.png"
            else:
                e[a] = None
        for a in ("walk", "idle", "cast", "hurt"):
            assert e[a], (n, a)
        chars[n] = e
    pools = {k: groups.get(k, []) for k in POOLS}
    named = groups.get("legacy", []) + groups.get("named", [])
    lines = ["// Generated by assets/tools/lpc_index.py - do not edit by hand.",
             "// LPC character sheets: 64x64 frames; rows = directions (dirRows); anchor = feet point inside a frame.",
             "// walk: col 0 = standing, cols 1-8 = walk cycle. idle: 2-frame breathing (static for outfits without idle art).",
             "// cast: LPC spellcast (arms raised; dance/cheer/fight). hurt: 1 row, falls down, last frame = lying (slip/sleep/pass out).",
             "// sit: 3 seated poses per direction, or null. Characters with art synthesised for cast/hurt are listed in 'synth'.",
             "window.CHAR_INDEX = {",
             "  frame: 64, anchor: [32, 60],",
             "  anims: { walk: {cols: 9, rows: 4}, idle: {cols: 2, rows: 4}, cast: {cols: 7, rows: 4}, hurt: {cols: 6, rows: 1}, sit: {cols: 3, rows: 4} },",
             "  fps: { walk: 10, idle: 2, cast: 8, hurt: 8, sit: 1 },",
             "  dirRows: { up: 0, left: 1, down: 2, right: 3 },",
             "  chars: {"]
    for n, e in chars.items():
        parts = ", ".join(f"{a}: " + (f"'{p}'" if p else "null") for a, p in e.items())
        lines.append(f"    {n}: {{ {parts} }},")
    lines.append("  },")
    lines.append("  groups: {")
    lines.append(f"    named: {json.dumps(named)},")
    lines.append(f"    staff: {json.dumps(groups.get('staff', []))},")
    lines.append("  },")
    lines.append("  pools: {")
    for k in POOLS:
        lines.append(f"    {k}: {json.dumps(pools[k])},")
    lines.append("  },")
    synth = [c["name"] for c in cfg["characters"] if c["body"] == "child"]
    lines.append(f"  synth: {json.dumps(synth)},  // children: cast = hop in place, hurt = topple over (no LPC child-clothes art)")
    lines.append("};")
    with open(os.path.join(CH, "index.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote characters/index.js:", len(chars), "characters,", {k: len(v) for k, v in pools.items()})
    return named, pools


def grid(names, out, title, scale=3, per_row=10):
    cell_w, lab = F * scale, 18
    fn = font(13)
    rows = (len(names) + per_row - 1) // per_row
    W, H = per_row * cell_w, 26 + rows * (F * scale + lab)
    sheet = Image.new("RGBA", (W, H), BG)
    d = ImageDraw.Draw(sheet)
    d.text((6, 4), title, fill=(255, 255, 255, 255), font=font(16))
    for i, n in enumerate(names):
        x, y = (i % per_row) * cell_w, 26 + (i // per_row) * (F * scale + lab)
        fr = frame(n, "walk", 0, 2).resize((F * scale, F * scale), Image.NEAREST)
        sheet.alpha_composite(fr, (x, y))
        tw = d.textlength(n, font=fn)
        d.text((x + (cell_w - tw) / 2, y + F * scale - 2), n, fill=(255, 255, 255, 255), font=fn)
    sheet.convert("RGB").save(out, optimize=True)
    print("wrote", os.path.relpath(out, ROOT), sheet.size)


def anim_sheet(names, out, scale=3):
    rows_spec = [("walk", 2, range(9), "walk down"), ("walk", 3, range(9), "walk right"), ("idle", 2, range(2), "idle down"),
                 ("cast", 2, range(7), "cast down"), ("cast", 1, range(7), "cast left"), ("hurt", 0, range(6), "hurt"),
                 ("sit", 2, range(3), "sit down"), ("sit", 3, range(3), "sit right")]
    lab_w = 110
    fn = font(13)
    blocks = []
    for n in names:
        for a, r, cols, label in rows_spec:
            if os.path.exists(os.path.join(CH, f"{n}_{a}.png")):
                blocks.append((n, a, r, cols, label))
    W = lab_w + 9 * F * scale
    H = len(blocks) * F * scale
    sheet = Image.new("RGBA", (W, H), BG)
    d = ImageDraw.Draw(sheet)
    for i, (n, a, r, cols, label) in enumerate(blocks):
        y = i * F * scale
        d.text((6, y + 70), f"{n}\n{label}", fill=(255, 255, 255, 255), font=fn)
        for j, c in enumerate(cols):
            sheet.alpha_composite(frame(n, a, c, r).resize((F * scale, F * scale), Image.NEAREST), (lab_w + j * F * scale, y))
        d.line([(0, y), (W, y)], fill=(70, 120, 60, 255))
    sheet.convert("RGB").save(out, optimize=True)
    print("wrote", os.path.relpath(out, ROOT), sheet.size)


def main():
    cfg = json.load(open(os.path.join(HERE, "lpc_characters.json"), encoding="utf-8"))
    named, pools = write_index(cfg)
    os.makedirs(PV, exist_ok=True)
    staff = cfg["groups"].get("staff", [])
    grid(named + staff, os.path.join(PV, "cast_named.png"), "Named characters + staff (walk col 0, facing down)")
    pool = [n for k in POOLS for n in pools[k]]
    grid(pool, os.path.join(PV, "cast_pool.png"), "Guest pool: m / f / om / of / kb / kg", per_row=12)
    anim_sheet(["groom", "bride"], os.path.join(PV, "cast_anims_groom_bride.png"))


if __name__ == "__main__":
    main()
