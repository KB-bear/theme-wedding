// Builds lang/ru.js from lang/todo.json (English, by index) + lang/ru-parts/*.txt ("index|Russian" lines),
// plus lang/ru-extra.txt ("English|Russian" lines) for hand-added patterns.
// Usage: node tools/build-lang.js
const fs = require('fs'), path = require('path');
const L = path.join(__dirname, '..', 'lang');
const en = JSON.parse(fs.readFileSync(path.join(L, 'todo.json'), 'utf8'));
const out = {};
let n = 0;
for (const f of fs.readdirSync(path.join(L, 'ru-parts')).sort()) {
  for (const line of fs.readFileSync(path.join(L, 'ru-parts', f), 'utf8').split(/\r?\n/)) {
    const m = /^(\d+)\|(.*)$/.exec(line); if (!m) continue;
    const e = en[+m[1]]; if (e === undefined) { console.warn('bad index', f, m[1]); continue; }
    const want = (e.match(/\{\d+\}/g) || []).sort().join(), got = (m[2].match(/\{\d+\}/g) || []).sort().join();
    if (want !== got) console.warn('placeholder mismatch', m[1], JSON.stringify(e), '->', JSON.stringify(m[2]));
    out[e] = m[2]; n++;
  }
}
const extra = path.join(L, 'ru-extra.txt');
if (fs.existsSync(extra)) for (const line of fs.readFileSync(extra, 'utf8').split(/\r?\n/)) {
  const i = line.indexOf('|'); if (i < 1 || line.startsWith('#')) continue;
  out[line.slice(0, i)] = line.slice(i + 1); n++;
}
fs.writeFileSync(path.join(L, 'ru.js'), '// Generated by tools/build-lang.js from lang/ru-parts and lang/ru-extra.txt - edit those.\nwindow.LANG_RU = ' + JSON.stringify(out, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log(n, 'translations');
